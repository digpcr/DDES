# Interface for the DDES workflow by Wim Trypsteen and Emile Roose.

ddes_ui <- function() {
  shiny::fluidPage(
    shiny::tags$style(".handsontable td { overflow-wrap: anywhere; }"),
    shiny::titlePanel("DDES Converter & Annotation Software"),
    shiny::sidebarLayout(
      shiny::sidebarPanel(width = 3,
        shiny::h4("Explore DDES data sets"),
        shiny::actionButton("start_demo", "Start QIAcuity Demo"),
        shiny::hr(),
        shiny::selectInput("platform", "Input format", c("DDES", "QIAcuity", "QX200 Quantasoft")),
        shiny::conditionalPanel("input.platform == 'DDES'",
          shiny::fileInput("ddes_upload", "DDES archive", accept = c(".ddes", ".zip"))),
        shiny::conditionalPanel("input.platform == 'QIAcuity'",
          shiny::fileInput("qi_results", "Analysis CSV", accept = ".csv"),
          shiny::fileInput("qi_layout", "Plate layout CSV", accept = ".csv"),
          shiny::fileInput("qi_rfu", "RFU CSV files (ZIP)", accept = ".zip")),
        shiny::conditionalPanel("input.platform == 'QX200 Quantasoft'",
          shiny::fileInput("qx_results", "Results CSV", accept = ".csv"),
          shiny::fileInput("qx_amplitudes", "Amplitude CSV files", accept = ".csv", multiple = TRUE)),
        shiny::actionButton("start", "Start DDES Conversion"),
        shiny::hr(),
        shiny::textOutput("status"),
        shiny::helpText("Edits stay in this browser session. Save each table before downloading.")),
      shiny::mainPanel(width = 9,
        shiny::tabsetPanel(id = "tabs",
          shiny::tabPanel("DDES Run Info", value = "run",
            shiny::h3("Run Information"),
            shiny::uiOutput("run_fields")),
          shiny::tabPanel("DDES Probe & Assay Annotation", value = "annotation",
            shiny::fluidRow(
              shiny::column(5,
                shiny::h3("Probe Information"),
                shiny::helpText("Edit target names, then save. Select probes to build an assay."),
                shiny::textInput("probe_target", "Target ID"),
                shiny::textInput("probe_channel", "Channel ID"),
                shiny::actionButton("add_probe", "Add Probe"),
                shiny::actionButton("delete_probe", "Delete Selected Probes"),
                shiny::actionButton("save_probes", "Save Probe Info"),
                rhandsontable::rHandsontableOutput("probes")),
              shiny::column(7,
                shiny::h3("Assay Information"),
                shiny::helpText("Edit assay names or concentrations, then save. Concentrations use semicolons and NA."),
                shiny::textInput("assay_name", "Assay ID"),
                shiny::actionButton("add_assay", "Add Assay From Selected Probes"),
                shiny::actionButton("delete_assay", "Delete Selected Assays"),
                shiny::actionButton("save_assays", "Save Assay Info"),
                shiny::hr(),
                shiny::helpText("Select one assay and its new probes in the probe table. Replacing probes clears its concentrations and affected reported results."),
                shiny::actionButton("replace_assay_probes", "Replace Selected Assay's Probes"),
                rhandsontable::rHandsontableOutput("assays")))),
          shiny::tabPanel("DDES Sample Annotation", value = "samples",
            shiny::h3("Sample Annotation"),
            shiny::helpText("Edit sample IDs and save. Select wells to assign an assay. A different assay clears their reported counts, concentrations, and thresholds; fluorescence is unchanged."),
            shiny::selectInput("sample_assay", "Assay", character()),
            shiny::actionButton("apply_assay", "Apply Assay to Selected Wells"),
            shiny::actionButton("save_samples", "Save Sample IDs"),
            rhandsontable::rHandsontableOutput("samples")),
          shiny::tabPanel("DDES Main", value = "main",
            shiny::h3("Main Metadata"), shiny::tableOutput("main_metadata"),
            shiny::h3("Results by Well and Target"), shiny::tableOutput("main_records")),
          shiny::tabPanel("DDES Assays", value = "assays",
            shiny::h3("Assays Metadata"), shiny::tableOutput("assays_metadata"),
            shiny::h3("Assay Definitions"), shiny::tableOutput("assays_records")),
          shiny::tabPanel("DDES Intensity Files", value = "intensity",
            shiny::selectInput("intensity_well", "Well", character()),
            shiny::h3("Intensity Metadata"), shiny::tableOutput("intensity_metadata"),
            shiny::h3("Endpoint Measurements (first 10 rows)"), shiny::tableOutput("intensity_records")),
          shiny::tabPanel("Download DDES Files", value = "download",
            shiny::h3("Download DDES Archive"),
            shiny::helpText("Downloads include saved edits only. All components are validated before download."),
            shiny::actionButton("prepare_download", "Validate Download"),
            shiny::uiOutput("download_link")),
          shiny::tabPanel("How To Use", value = "help",
            shiny::h3("Convert, Annotate, and Download"),
            shiny::tags$ol(
              shiny::tags$li("Load the demo or select an input format, upload its files, and start conversion."),
              shiny::tags$li("Review run metadata. Save changes to update every component's experiment and run identifiers."),
              shiny::tags$li("Add probes, select them to create assays, and edit names and concentrations. Save each table."),
              shiny::tags$li("Edit sample IDs or assign assays to selected wells. Assigning a different assay clears reported results for those wells."),
              shiny::tags$li("Inspect the main, assays, and intensity tabs; validate and download the saved dataset.")),
            shiny::p("In-use probes and assays cannot be deleted. No clustering or result recalculation is performed."),
            shiny::p("The converter and annotation workflow is by Wim Trypsteen and Emile Roose, DIGPCR UGent."))))
    )
  )
}
